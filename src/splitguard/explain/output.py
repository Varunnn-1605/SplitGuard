"""Validate the model's answer and turn it into an ``Explanation``.

Validation is strict: an answer that is empty, too long, not JSON, missing
fields or carrying unexpected fields is rejected (``InvalidModelOutputError``)
and nothing is shown. Inside a valid answer:

* explanations for finding IDs that were not supplied are dropped and listed in
  ``rejected_finding_ids`` - the model cannot add findings;
* severity, confidence and title always come from the audit report, never from
  the model - the model cannot reclassify findings;
* long fields are truncated;
* deterministic checks add ``review_flags`` when the text overstates certainty,
  names a severity or confidence that differs from the report, or skips the
  coverage section although checks did not run.

These checks reduce, but cannot eliminate, the risk of a misleading narrative.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Any

from splitguard.explain.errors import InvalidModelOutputError
from splitguard.explain.payload import clean_text
from splitguard.explain.prompt import FINDING_FIELDS, TOP_LEVEL_FIELDS

MAX_RESPONSE_CHARS = 24_000
FIELD_LIMITS = {
    "overview": 1_200,
    "coverage": 1_200,
    "caveats": 800,
    "why_it_matters": 700,
    "evidence": 700,
    "what_to_check": 700,
    "limitations": 700,
}
DISCLAIMER = (
    "Generated by a local language model from the summarised audit report. It is not an "
    "audit finding, may be wrong or incomplete, and must be checked against the original "
    "findings and evidence."
)
_LEVEL = r"(critical|high|medium|low|info)"
_SEVERITY_MENTION = re.compile(
    rf"\b{_LEVEL}[- ]severity\b|\bseverity\s*(?:is|of|:|=|rated|level)?\s*(?:as\s+)?{_LEVEL}\b",
    re.I,
)
_CONFIDENCE_MENTION = re.compile(
    r"\b(high|medium|low)[- ]confidence\b|\bconfidence\s*(?:is|of|:|=|rated|level)?\s*"
    r"(?:as\s+)?(high|medium|low)\b",
    re.I,
)
_OVERCLAIMS = (
    re.compile(r"\bleak(?:age)?[- ]free\b", re.I),
    re.compile(r"\b(?:the\s+)?(?:dataset|data|split)\s+is\s+(?:safe|clean)\b", re.I),
    re.compile(r"\bno\s+(?:data\s+)?leakage\b", re.I),
    re.compile(r"\b(?:proves?|proven|confirms?|guarantees?)\b[^.]{0,40}\bleak", re.I),
    re.compile(r"\bdefinitely\b|\bcertainly\b|\bwithout (?:a )?doubt\b", re.I),
)
_NEGATION = re.compile(r"\b(?:not|never|cannot|can't|doesn't|does not|no findings)\b", re.I)


@dataclass(frozen=True)
class FindingExplanation:
    """Narrative for one finding. ``severity``, ``confidence``, ``title`` and
    ``evidence_kind`` are copied from the audit report, not from the model."""

    finding_id: str
    severity: str
    confidence: str
    evidence_kind: str
    title: str
    why_it_matters: str
    evidence: str
    what_to_check: str
    limitations: str

    def to_dict(self) -> dict[str, str]:
        return dict(self.__dict__)


@dataclass(frozen=True)
class Explanation:
    """A validated, non-authoritative narrative about an audit report."""

    model: str
    overview: str
    findings: tuple[FindingExplanation, ...]
    coverage: str
    caveats: str
    unexplained_finding_ids: tuple[str, ...] = ()
    rejected_finding_ids: tuple[str, ...] = ()
    findings_not_sent: tuple[str, ...] = ()
    review_flags: tuple[str, ...] = ()
    truncated_fields: tuple[str, ...] = field(default_factory=tuple)

    def to_dict(self) -> dict[str, Any]:
        return {
            "kind": "splitguard_llm_explanation",
            "authoritative": False,
            "disclaimer": DISCLAIMER,
            "model": self.model,
            "overview": self.overview,
            "findings": [f.to_dict() for f in self.findings],
            "coverage": self.coverage,
            "caveats": self.caveats,
            "unexplained_finding_ids": list(self.unexplained_finding_ids),
            "rejected_finding_ids": list(self.rejected_finding_ids),
            "findings_not_sent": list(self.findings_not_sent),
            "review_flags": list(self.review_flags),
            "truncated_fields": list(self.truncated_fields),
        }


def _load(raw: Any) -> dict[str, Any]:
    if not isinstance(raw, str) or not raw.strip():
        raise InvalidModelOutputError("The model returned an empty answer.")
    if len(raw) > MAX_RESPONSE_CHARS:
        raise InvalidModelOutputError("The model's answer was longer than allowed.")
    text = raw.strip()
    fence = re.fullmatch(r"```(?:json)?\s*(.*?)\s*```", text, re.S)
    if fence:
        text = fence.group(1)
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        raise InvalidModelOutputError("The model's answer was not valid JSON.") from None
    if not isinstance(data, dict):
        raise InvalidModelOutputError("The model's answer was not a JSON object.")
    return data


def _check_keys(obj: dict[str, Any], expected: tuple[str, ...], where: str) -> None:
    keys = set(obj)
    missing = [k for k in expected if k not in keys]
    unexpected = sorted(keys - set(expected))
    if missing:
        raise InvalidModelOutputError(f"The model's answer is missing {where} field(s): {missing}.")
    if unexpected:
        shown = [clean_text(k, 30) for k in unexpected[:5]]
        raise InvalidModelOutputError(
            f"The model's answer has unexpected {where} field(s): {shown}."
        )


def _text(obj: dict[str, Any], key: str, truncated: list[str], label: str) -> str:
    value = obj[key]
    if not isinstance(value, str):
        raise InvalidModelOutputError(f"The model's '{key}' field is not text.")
    limit = FIELD_LIMITS[key]
    text = clean_text(value, limit)
    if len(clean_text(value, 10**6)) > limit:
        truncated.append(label)
    return text


def _overclaims(text: str) -> bool:
    for pattern in _OVERCLAIMS:
        for match in pattern.finditer(text):
            window = text[max(0, match.start() - 30) : match.start()]
            if not _NEGATION.search(window) and not _NEGATION.search(match.group(0)):
                return True
    return False


def _mismatch(text: str, pattern: re.Pattern[str], canonical: str) -> bool:
    for match in pattern.finditer(text):
        level = next(g for g in match.groups() if g)
        if level.lower() != canonical:
            return True
    return False


def parse_response(raw: Any, payload: dict[str, Any], model: str) -> Explanation:
    """Validate ``raw`` (the model's JSON text) against the supplied ``payload``."""
    data = _load(raw)
    _check_keys(data, TOP_LEVEL_FIELDS, "top-level")
    truncated: list[str] = []
    overview = _text(data, "overview", truncated, "overview")
    coverage = _text(data, "coverage", truncated, "coverage")
    caveats = _text(data, "caveats", truncated, "caveats")
    items = data["findings"]
    if not isinstance(items, list):
        raise InvalidModelOutputError("The model's 'findings' field is not a list.")
    supplied = {f["finding_id"]: f for f in payload["findings"]}
    if len(items) > max(len(supplied), 1) * 2:
        raise InvalidModelOutputError("The model returned far more explanations than findings.")

    explained: dict[str, FindingExplanation] = {}
    rejected: list[str] = []
    flags: list[str] = []
    for item in items:
        if not isinstance(item, dict):
            raise InvalidModelOutputError("An entry in the model's 'findings' is not an object.")
        _check_keys(item, FINDING_FIELDS, "finding")
        fid = item["finding_id"]
        if not isinstance(fid, str) or fid not in supplied:
            rejected.append(clean_text(fid, 80))
            continue
        if fid in explained:
            continue
        canon = supplied[fid]
        texts = {k: _text(item, k, truncated, f"{fid}.{k}") for k in FINDING_FIELDS[1:]}
        joined = " ".join(texts.values())
        if _mismatch(joined, _SEVERITY_MENTION, canon["severity"]):
            flags.append(f"{fid}: the narrative names a severity that differs from the report.")
        if _mismatch(joined, _CONFIDENCE_MENTION, canon["confidence"]):
            flags.append(f"{fid}: the narrative names a confidence that differs from the report.")
        explained[fid] = FindingExplanation(
            finding_id=fid,
            severity=canon["severity"],
            confidence=canon["confidence"],
            evidence_kind=canon["evidence_kind"],
            title=canon["title"],
            **texts,
        )

    all_text = " ".join(
        [overview, coverage, caveats]
        + [" ".join((e.why_it_matters, e.evidence, e.what_to_check)) for e in explained.values()]
    )
    if _overclaims(all_text):
        flags.append(
            "The narrative may overstate certainty (for example calling the data safe or a "
            "finding proven). Rely on the findings' severity and confidence instead."
        )
    if rejected:
        flags.append(
            f"{len(rejected)} explanation(s) referred to finding IDs that are not in the report "
            "and were discarded."
        )
    not_assessed = bool(payload["checks_not_run"] or payload["warnings"])
    if not_assessed and len(coverage) < 20:
        flags.append(
            "Some checks did not run or had partial coverage, but the narrative does not "
            "explain this. See 'What was not fully assessed' in the report."
        )
    if not (overview or coverage or explained):
        raise InvalidModelOutputError("The model's answer contained no usable explanation.")
    # Keep the report's order (most severe first), not the model's.
    ordered = tuple(
        explained[f["finding_id"]] for f in payload["findings"] if f["finding_id"] in explained
    )
    return Explanation(
        model=model,
        overview=overview,
        findings=ordered,
        coverage=coverage,
        caveats=caveats,
        unexplained_finding_ids=tuple(f for f in supplied if f not in explained),
        rejected_finding_ids=tuple(rejected),
        findings_not_sent=tuple(payload.get("findings_not_sent", ())),
        review_flags=tuple(flags),
        truncated_fields=tuple(truncated),
    )


def render_text(explanation: Explanation) -> str:
    """Plain-text rendering for the terminal, clearly labelled as non-authoritative."""
    lines = [
        "=" * 72,
        f"LLM-GENERATED EXPLANATION (model: {explanation.model}) - NOT AN AUDIT FINDING",
        DISCLAIMER,
        "=" * 72,
        "",
        explanation.overview,
    ]
    for f in explanation.findings:
        lines += [
            "",
            f"[{f.severity.upper()} severity | {f.confidence} confidence | {f.evidence_kind}] "
            f"{f.finding_id}  (from the audit report)",
            f"  {f.title}",
            f"  Why it matters: {f.why_it_matters}",
            f"  Evidence:       {f.evidence}",
            f"  What to check:  {f.what_to_check}",
            f"  Limitations:    {f.limitations}",
        ]
    lines += ["", f"Coverage: {explanation.coverage}", f"Caveats: {explanation.caveats}"]
    if explanation.unexplained_finding_ids:
        lines.append(
            "Not explained by the model (see the report): "
            + ", ".join(explanation.unexplained_finding_ids)
        )
    if explanation.findings_not_sent:
        lines.append(
            "Not sent to the model (size limit; see the report): "
            + ", ".join(explanation.findings_not_sent)
        )
    for flag in explanation.review_flags:
        lines.append(f"REVIEW: {flag}")
    return "\n".join(lines)
