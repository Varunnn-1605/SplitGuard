"""Run the adversarial validation cases and print a detection matrix.

Usage:
    python validation/run_validation.py [--markdown validation/RESULTS.md]

Scoring follows the unit of evaluation defined in ``validation/cases.py``:
one case = one injected (or absent) condition, scored once. Results describe
behaviour on synthetic controls only, not real-world accuracy.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from cases import build_cases  # noqa: E402

DETECTORS = ["duplicates", "target", "temporal", "identifiers", "schema", "validation"]


def evaluate() -> list[dict]:
    rows = []
    for case in build_cases():
        passed, details, outcome = case.evaluate()
        if case.kind == "positive":
            label = "TP" if passed else "FN"
        elif case.kind == "negative":
            label = "TN" if passed else "FP"
        else:
            label = "PASS" if passed else "FAIL"
        observed = (
            sorted(
                f"{f.finding_id} ({f.severity.value}/{f.confidence.value})"
                for f in outcome.result.findings
            )
            if outcome.result is not None
            else [f"validation error: {sorted(i.code for i in outcome.error.issues)}"]
        )
        rows.append(
            {
                "case": case.case_id,
                "detector": case.detector,
                "kind": case.kind,
                "description": case.description,
                "reason": case.reason,
                "label": label,
                "designated": case.designated,
                "checks": details,
                "observed": observed,
                "tags": case.tags,
            }
        )
    return rows


def matrix(rows: list[dict]) -> dict[str, dict[str, int]]:
    out: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in rows:
        out[r["detector"]][r["label"]] += 1
        out["ALL"][r["label"]] += 1
    return out


def render(rows: list[dict]) -> str:
    m = matrix(rows)
    lines = [
        "# SplitGuard adversarial validation results",
        "",
        "Generated by `python validation/run_validation.py --markdown validation/RESULTS.md`.",
        "Synthetic controls only: these counts check rule behaviour, not real-world accuracy.",
        "Unit: one case = one injected (or absent) condition, scored once against its designated rule;",
        "overlapping findings on the same rows are not counted as extra detections.",
        "",
        "| Detector | TP | FN | TN | FP | Boundary pass | Boundary fail |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for det in [*DETECTORS, "ALL"]:
        c = m.get(det, {})
        if not c:
            continue
        lines.append(
            f"| {det} | {c.get('TP', 0)} | {c.get('FN', 0)} | {c.get('TN', 0)} | {c.get('FP', 0)} "
            f"| {c.get('PASS', 0)} | {c.get('FAIL', 0)} |"
        )
    lines += [
        "",
        "Boundary and diagnostic cases are counted under *Boundary pass/fail*.",
        "",
        "## Cases",
        "",
        "| Case | Kind | Detector | Result | Condition | Expected behaviour (reason) | Observed findings |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        observed = "<br>".join(r["observed"]) or "none"
        lines.append(
            f"| {r['case']} | {r['kind']} | {r['detector']} | **{r['label']}** | {r['description']} "
            f"| {r['reason']} | {observed} |"
        )
    failures = [r for r in rows if r["label"] in {"FN", "FP", "FAIL"}]
    if failures:
        lines += ["", "## Failing expectations", ""]
        for r in failures:
            for ok, msg in r["checks"]:
                if not ok:
                    lines.append(f"- {r['case']}: {msg}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--markdown", type=Path, help="write the results table to this file")
    args = parser.parse_args()
    rows = evaluate()
    text = render(rows)
    if args.markdown:
        args.markdown.write_text(text, encoding="utf-8")
    m = matrix(rows)["ALL"]
    print(
        f"cases={len(rows)} TP={m.get('TP', 0)} FN={m.get('FN', 0)} TN={m.get('TN', 0)} "
        f"FP={m.get('FP', 0)} boundary_pass={m.get('PASS', 0)} boundary_fail={m.get('FAIL', 0)}"
    )
    for r in rows:
        if r["label"] in {"FN", "FP", "FAIL"}:
            print(
                f"  {r['label']} {r['case']}: "
                + "; ".join(msg for ok, msg in r["checks"] if not ok)
            )
    return 0 if all(r["label"] in {"TP", "TN", "PASS"} for r in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
